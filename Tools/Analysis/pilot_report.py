"""LinguaSpy pilot report: telemetry JSONL (+ survey CSV) -> pilot_report.md + SVG charts.
Standard library only (no pandas/matplotlib), so it runs on any machine with Python 3.9+.

    python Tools/Analysis/pilot_report.py --logs <folder with *.jsonl> [--survey survey.csv] [--out <folder>]
    python Tools/Analysis/pilot_report.py --selftest      # synthetic data, to check the pipeline ONLY

Survey CSV columns (one row per participant; Likert 1-5):
    participant,sus1,...,sus10,want_more,nervous,handler_useful,real_life,best,confusing

What it reports (docs/Pilot_Study_Protocol.md section 6):
- pre / post / delayed scores per participant, paired t-test and exact Wilcoxon signed-rank, Cohen's d_z with 95% CI
- first-try accuracy by scaffold level and by skill, helper reliance (peeks / prompts) over the session
- where cover was blown, briefing -> field transfer, SUS and engagement items
Single-group pre/post: the report says so, and it never claims the game beats anything else.
"""
import argparse
import csv
import glob
import json
import math
import os
import random
import statistics
import sys
from collections import Counter, defaultdict

SYNTHETIC_BANNER = "SYNTHETIC DATA - NOT RESULTS. Generated by --selftest to check the analysis pipeline."


# ---- statistics (stdlib) ----------------------------------------------------------------------------------------

def _betacf(a, b, x):
    # Continued fraction for the incomplete beta (Numerical Recipes)
    qab, qap, qam = a + b, a + 1.0, a - 1.0
    c, d = 1.0, 1.0 - qab * x / qap
    d = 1.0 / (d if abs(d) > 1e-300 else 1e-300)
    h = d
    for m in range(1, 300):
        m2 = 2 * m
        aa = m * (b - m) * x / ((qam + m2) * (a + m2))
        d = 1.0 + aa * d
        d = 1.0 / (d if abs(d) > 1e-300 else 1e-300)
        c = 1.0 + aa / c if abs(c) > 1e-300 else 1e300
        h *= d * c
        aa = -(a + m) * (qab + m) * x / ((a + m2) * (qap + m2))
        d = 1.0 + aa * d
        d = 1.0 / (d if abs(d) > 1e-300 else 1e-300)
        c = 1.0 + aa / c if abs(c) > 1e-300 else 1e300
        delta = d * c
        h *= delta
        if abs(delta - 1.0) < 1e-12:
            break
    return h


def betainc(a, b, x):
    if x <= 0:
        return 0.0
    if x >= 1:
        return 1.0
    lbeta = math.lgamma(a + b) - math.lgamma(a) - math.lgamma(b) + a * math.log(x) + b * math.log(1 - x)
    if x < (a + 1) / (a + b + 2):
        return math.exp(lbeta) * _betacf(a, b, x) / a
    return 1.0 - math.exp(lbeta) * _betacf(b, a, 1 - x) / b


def t_sf2(t, df):
    """Two-sided p-value for Student's t."""
    return betainc(df / 2.0, 0.5, df / (df + t * t))


def t_crit(df, alpha=0.05):
    lo, hi = 0.0, 50.0
    for _ in range(100):
        mid = (lo + hi) / 2
        if t_sf2(mid, df) > alpha:
            lo = mid
        else:
            hi = mid
    return (lo + hi) / 2


def paired_stats(pairs):
    """pairs: [(before, after)] -> dict with mean diff, d_z, CI, t, p (two-sided), Wilcoxon exact p."""
    diffs = [b - a for a, b in pairs]
    n = len(diffs)
    out = {"n": n}
    if n < 2:
        return out
    md = statistics.mean(diffs)
    sd = statistics.stdev(diffs)
    out.update(mean_before=statistics.mean(a for a, _ in pairs), mean_after=statistics.mean(b for _, b in pairs),
               sd_before=statistics.stdev(a for a, _ in pairs), sd_after=statistics.stdev(b for _, b in pairs),
               mean_diff=md, sd_diff=sd)
    if sd > 0:
        se = sd / math.sqrt(n)
        t = md / se
        tc = t_crit(n - 1)
        out.update(t=t, df=n - 1, p=t_sf2(abs(t), n - 1), ci=(md - tc * se, md + tc * se),
                   d_z=md / sd, d_z_ci=((md - tc * se) / sd, (md + tc * se) / sd))
    out["wilcoxon_p"] = wilcoxon_exact(diffs)
    return out


def wilcoxon_exact(diffs):
    """Exact two-sided Wilcoxon signed-rank p (zeros dropped, average ranks for ties, DP over rank sums)."""
    d = [x for x in diffs if x != 0]
    n = len(d)
    if n == 0:
        return 1.0
    order = sorted(range(n), key=lambda i: abs(d[i]))
    ranks = [0.0] * n
    i = 0
    while i < n:
        j = i
        while j + 1 < n and abs(d[order[j + 1]]) == abs(d[order[i]]):
            j += 1
        for k in range(i, j + 1):
            ranks[order[k]] = (i + j) / 2 + 1
        i = j + 1
    w_plus = sum(r for r, x in zip(ranks, d) if x > 0)
    # Work in half-ranks so ties stay integers
    r2 = [int(round(r * 2)) for r in ranks]
    total = sum(r2)
    dist = [0] * (total + 1)
    dist[0] = 1
    for r in r2:
        for s in range(total, r - 1, -1):
            dist[s] += dist[s - r]
    count = 2 ** n
    obs = int(round(w_plus * 2))
    mean = total / 2
    extreme = abs(obs - mean)
    p = sum(c for s, c in enumerate(dist) if abs(s - mean) >= extreme - 1e-9) / count
    return min(1.0, p)


def sus_score(row):
    vals = [float(row[f"sus{i}"]) for i in range(1, 11)]
    return 2.5 * sum((v - 1) if i % 2 == 0 else (5 - v) for i, v in enumerate(vals))


# ---- loading ----------------------------------------------------------------------------------------------------

def load_events(folder):
    events = []
    for path in sorted(glob.glob(os.path.join(folder, "**", "*.jsonl"), recursive=True)):
        with open(path, encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if line:
                    try:
                        events.append(json.loads(line))
                    except json.JSONDecodeError:
                        print(f"warning: bad line in {path}", file=sys.stderr)
    events.sort(key=lambda e: (e.get("participant", ""), e.get("t", "")))
    return events


def load_survey(path):
    if not path or not os.path.exists(path):
        return []
    with open(path, encoding="utf-8-sig") as f:
        return list(csv.DictReader(f))


# ---- charts (plain SVG) -----------------------------------------------------------------------------------------

def svg_bars(path, title, labels, values, maxv=1.0, fmt="{:.0%}"):
    w, h, pad, bw = 640, 300, 40, max(18, int(520 / max(len(values), 1)) - 10)
    out = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" font-family="sans-serif" font-size="12">',
           f'<text x="{pad}" y="20" font-size="14" font-weight="bold">{title}</text>',
           f'<line x1="{pad}" y1="{h - 50}" x2="{w - 10}" y2="{h - 50}" stroke="#888"/>']
    for i, (lab, v) in enumerate(zip(labels, values)):
        x = pad + 10 + i * (bw + 10)
        bh = 0 if maxv == 0 else (h - 90) * (v / maxv)
        out.append(f'<rect x="{x}" y="{h - 50 - bh:.1f}" width="{bw}" height="{bh:.1f}" fill="#4C78A8"/>')
        out.append(f'<text x="{x + bw / 2}" y="{h - 55 - bh:.1f}" text-anchor="middle">{fmt.format(v)}</text>')
        out.append(f'<text x="{x + bw / 2}" y="{h - 32}" text-anchor="middle">{lab}</text>')
    out.append("</svg>")
    open(path, "w", encoding="utf-8").write("\n".join(out))


def svg_paired(path, title, rows, phases):
    """One line per participant across phases (scores as share of max)."""
    w, h, pad = 640, 320, 50
    xs = {p: pad + 40 + i * ((w - 2 * pad - 80) / max(len(phases) - 1, 1)) for i, p in enumerate(phases)}
    y = lambda v: h - 40 - (h - 80) * v
    out = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" font-family="sans-serif" font-size="12">',
           f'<text x="{pad}" y="20" font-size="14" font-weight="bold">{title}</text>']
    for v in (0, 0.5, 1):
        out.append(f'<line x1="{pad}" y1="{y(v)}" x2="{w - 10}" y2="{y(v)}" stroke="#ddd"/>')
        out.append(f'<text x="{pad - 6}" y="{y(v) + 4}" text-anchor="end">{v:.0%}</text>')
    for p, x in xs.items():
        out.append(f'<text x="{x}" y="{h - 18}" text-anchor="middle">{p}</text>')
    for scores in rows.values():
        pts = [(xs[p], y(scores[p])) for p in phases if p in scores]
        if len(pts) > 1:
            out.append('<polyline fill="none" stroke="#4C78A8" stroke-opacity="0.5" points="' +
                       " ".join(f"{a:.1f},{b:.1f}" for a, b in pts) + '"/>')
        for a, b in pts:
            out.append(f'<circle cx="{a:.1f}" cy="{b:.1f}" r="3" fill="#4C78A8"/>')
    out.append("</svg>")
    open(path, "w", encoding="utf-8").write("\n".join(out))


# ---- report -----------------------------------------------------------------------------------------------------

def fmt_p(p):
    return "p < .001" if p < 0.001 else f"p = {p:.3f}"


def build_report(events, survey, out_dir, synthetic=False):
    os.makedirs(out_dir, exist_ok=True)
    md = []
    if synthetic:
        md += [f"# {SYNTHETIC_BANNER}", ""]
    md += ["# LinguaSpy pilot report", ""]
    participants = sorted({e.get("participant", "anon") for e in events})
    md.append(f"Participants with logs: **{len(participants)}** ({', '.join(participants)}). Events: {len(events)}.")
    md.append("")
    md.append("> Design: single group, pre-test -> play -> post-test (+ 1-week delayed test), parallel forms counterbalanced. "
              "Gains show change over the session; without a control group they do not show that LinguaSpy beats other methods.")
    md.append("")

    # Assessments: latest result per participant + phase
    scores = defaultdict(dict)
    for e in events:
        if e["event"] == "assessment_end" and e.get("max"):
            scores[e["participant"]][e["phase"]] = e["score"] / e["max"]
    md += ["## Learning: test scores", ""]
    md.append("| Participant | Pre | Post | Delayed |")
    md.append("|---|---|---|---|")
    for p in participants:
        s = scores.get(p, {})
        md.append(f"| {p} | " + " | ".join(f"{s[k]:.0%}" if k in s else "-" for k in ("Pre", "Post", "Delayed")) + " |")
    md.append("")
    for a, b, label in (("Pre", "Post", "Immediate gain (post - pre)"), ("Pre", "Delayed", "Retention (delayed - pre)"),
                        ("Post", "Delayed", "Forgetting (delayed - post)")):
        pairs = [(s[a], s[b]) for s in scores.values() if a in s and b in s]
        st = paired_stats(pairs)
        if st.get("n", 0) < 2 or "d_z" not in st:
            md.append(f"- **{label}**: not enough paired data (n = {st.get('n', 0)}).")
            continue
        md.append(f"- **{label}** (n = {st['n']}): {st['mean_before']:.0%} (SD {st['sd_before']:.0%}) -> "
                  f"{st['mean_after']:.0%} (SD {st['sd_after']:.0%}); mean change {st['mean_diff']:+.1%} "
                  f"[95% CI {st['ci'][0]:+.1%}, {st['ci'][1]:+.1%}]; paired t({st['df']}) = {st['t']:.2f}, {fmt_p(st['p'])}; "
                  f"Wilcoxon exact {fmt_p(st['wilcoxon_p'])}; d_z = {st['d_z']:.2f} (approx. CI {st['d_z_ci'][0]:.2f} to {st['d_z_ci'][1]:.2f}).")
    md.append("")
    md.append("Effect-size yardstick for within-group L2 studies (Plonsky & Oswald, 2014): about 0.6 small, 1.0 medium, 1.4 large.")
    md.append("")
    if scores:
        svg_paired(os.path.join(out_dir, "scores.svg"), "Test score per participant", scores, ["Pre", "Post", "Delayed"])
        md += ["![Scores](scores.svg)", ""]

    # In-game learning process
    ch = [e for e in events if e["event"] == "challenge" and e.get("mode") == "conversation"]
    md += ["## How they learned (gameplay telemetry)", ""]
    if ch:
        first = lambda rows: sum(1 for r in rows if r["passed"] and r["attempts"] == 1) / len(rows)
        by_level = defaultdict(list)
        for r in ch:
            by_level[r["level"]].append(r)
        levels = [l for l in ("Recognize", "Assemble", "AssemblePlus", "GapFill", "Produce") if l in by_level]
        md.append("| Scaffold level | Answers | First-try correct | Needed the hint | Missed after hint |")
        md.append("|---|---|---|---|---|")
        for l in levels:
            rows = by_level[l]
            md.append(f"| {l} | {len(rows)} | {first(rows):.0%} | "
                      f"{sum(1 for r in rows if r['passed'] and r['attempts'] > 1) / len(rows):.0%} | "
                      f"{sum(1 for r in rows if not r['passed']) / len(rows):.0%} |")
        svg_bars(os.path.join(out_dir, "levels.svg"), "First-try accuracy by scaffold level", levels, [first(by_level[l]) for l in levels])
        md += ["", "![Levels](levels.svg)", ""]

        by_skill = defaultdict(list)
        for r in ch:
            by_skill[r.get("skill", "?")].append(r)
        md.append("| Skill | Answers | First-try correct | Avg. answer time |")
        md.append("|---|---|---|---|")
        for s, rows in sorted(by_skill.items(), key=lambda kv: first(kv[1])):
            md.append(f"| {s} | {len(rows)} | {first(rows):.0%} | {statistics.mean(r.get('ms', 0) for r in rows) / 1000:.1f} s |")
        md.append("")

        # Reliance over the session: help (peek or hint) per answer, by thirds of each participant's answers
        thirds = [[], [], []]
        for p in participants:
            rows = [r for r in ch if r["participant"] == p]
            for i, r in enumerate(rows):
                thirds[min(2, i * 3 // max(len(rows), 1))].append(1 if (r.get("peeked") or r["attempts"] > 1) else 0)
        rel = [statistics.mean(t) if t else 0 for t in thirds]
        md.append(f"Help needed per answer (translation peek or hint), by part of the session: "
                  f"first third {rel[0]:.0%}, middle {rel[1]:.0%}, last third {rel[2]:.0%}.")
        svg_bars(os.path.join(out_dir, "reliance.svg"), "Help needed per answer over the session", ["start", "middle", "end"], rel)
        md += ["", "![Reliance](reliance.svg)", ""]
    else:
        md += ["No in-conversation challenges logged.", ""]

    intel = [e for e in events if e["event"] == "intel_check" and e.get("attempt") == 1]
    if intel:
        md.append(f"Listening checks (intel) right on the first try: {sum(e['correct'] for e in intel) / len(intel):.0%} of {len(intel)}.")
        md.append("")
    brief = [e for e in events if e["event"] == "briefing_item" and not e.get("retry")]
    if brief and ch:
        md.append(f"Briefing quiz first-try accuracy: {sum(e['correct'] for e in brief) / len(brief):.0%} "
                  f"({len(brief)} items) vs. first-try accuracy in conversations: {first(ch):.0%}.")
        md.append("")

    blown = Counter(f"{e.get('conversation')} / {e.get('node')}" for e in events if e["event"] == "cover_blown")
    md += ["## Where cover was blown", ""]
    md += ([f"- {k}: {v}" for k, v in blown.most_common(10)] or ["- never"]) + [""]

    sessions = defaultdict(list)
    for e in events:
        sessions[(e["participant"], e["session"])].append(e.get("t_ms", 0))
    if sessions:
        mins = [max(v) / 60000 for v in sessions.values()]
        md.append(f"Session length: median {statistics.median(mins):.0f} min (range {min(mins):.0f}-{max(mins):.0f}).")
        md.append("")

    # Survey
    md += ["## Usability and engagement (survey)", ""]
    if survey:
        sus = [sus_score(r) for r in survey if all(r.get(f"sus{i}") for i in range(1, 11))]
        if sus:
            md.append(f"- SUS: mean {statistics.mean(sus):.1f} (SD {statistics.stdev(sus) if len(sus) > 1 else 0:.1f}, n = {len(sus)}). "
                      "68 is the usual average; above 80 is good.")
        for key, label in (("want_more", "I wanted to keep playing"), ("nervous", "I felt nervous answering"),
                           ("handler_useful", "The handler's help was useful"), ("real_life", "I could say these phrases in real life")):
            vals = [float(r[key]) for r in survey if r.get(key)]
            if vals:
                md.append(f"- \"{label}\": mean {statistics.mean(vals):.1f} / 5; {sum(v >= 4 for v in vals) / len(vals):.0%} agree (4-5).")
        for key, label in (("best", "Best part"), ("confusing", "Most confusing")):
            answers = [r[key].strip() for r in survey if r.get(key, "").strip()]
            if answers:
                md += ["", f"**{label}:**"] + [f"- {a}" for a in answers]
    else:
        md.append("No survey file given.")
    md.append("")

    report = os.path.join(out_dir, "pilot_report.md")
    open(report, "w", encoding="utf-8").write("\n".join(md))
    return report


# ---- synthetic self-test ------------------------------------------------------------------------------------------

def synthesize(folder, survey_path, n=12, seed=7):
    """Fake logs + survey with a known structure. ONLY for checking that the pipeline runs."""
    rng = random.Random(seed)
    os.makedirs(folder, exist_ok=True)
    rows = []
    for i in range(n):
        p = f"SYN-{i:02d}"
        ev = []
        t = 0

        def add(name, **kw):
            nonlocal t
            t += rng.randint(2000, 15000)
            ev.append({"t": f"2000-01-01T00:{t // 60000 % 60:02d}:{t // 1000 % 60:02d}Z", "t_ms": t, "session": "syn",
                       "participant": p, "event": name, **kw})

        pre = rng.randint(3, 8)
        add("assessment_end", form="FR_A", phase="Pre", score=pre, max=15)
        for k in range(30):
            level = rng.choice(["Recognize", "Assemble", "Assemble", "AssemblePlus"])
            ok = rng.random() < 0.55 + k * 0.01
            add("challenge", mode="conversation", level=level, skill=rng.choice(["Ordering", "Directions", "Numbers"]),
                attempts=1 if ok else 2, passed=ok or rng.random() < 0.6, peeked=rng.random() < 0.3 - k * 0.008, ms=rng.randint(3000, 15000))
        add("intel_check", attempt=1, correct=rng.random() < 0.7)
        add("briefing_item", correct=rng.random() < 0.8, retry=False)
        add("assessment_end", form="FR_B", phase="Post", score=min(15, pre + rng.randint(-1, 6)), max=15)
        add("assessment_end", form="FR_A", phase="Delayed", score=min(15, pre + rng.randint(-2, 4)), max=15)
        with open(os.path.join(folder, f"{p}_syn.jsonl"), "w", encoding="utf-8") as f:
            for e in ev:
                f.write(json.dumps(e) + "\n")
        row = {"participant": p, **{f"sus{j}": str(rng.randint(1, 5)) for j in range(1, 11)},
               "want_more": str(rng.randint(2, 5)), "nervous": str(rng.randint(1, 4)), "handler_useful": str(rng.randint(2, 5)),
               "real_life": str(rng.randint(2, 5)), "best": "synthetic", "confusing": "synthetic"}
        rows.append(row)
    with open(survey_path, "w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)


def selftest():
    # Known-answer checks for the statistics
    assert abs(t_sf2(2.262, 9) - 0.05) < 0.002, t_sf2(2.262, 9)
    assert abs(t_crit(9) - 2.262) < 0.002
    assert abs(wilcoxon_exact([1, 2, 3, 4, 5]) - 0.0625) < 1e-9
    st = paired_stats([(0.2, 0.5), (0.3, 0.6), (0.4, 0.5), (0.5, 0.9)])
    assert st["mean_diff"] > 0 and st["p"] < 0.05, st
    assert sus_score({**{f"sus{i}": "5" if i % 2 else "1" for i in range(1, 11)}}) == 100.0

    root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "Saved", "PilotReport_SELFTEST")
    root = os.path.normpath(root)
    logs = os.path.join(root, "logs")
    survey = os.path.join(root, "survey_SYNTHETIC.csv")
    synthesize(logs, survey)
    report = build_report(load_events(logs), load_survey(survey), os.path.join(root, "report"), synthetic=True)
    text = open(report, encoding="utf-8").read()
    assert text.startswith("# " + SYNTHETIC_BANNER)
    print(f"selftest ok -> {report} (synthetic; never use these numbers)")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--logs", help="folder with telemetry *.jsonl (searched recursively)")
    ap.add_argument("--survey", help="survey CSV")
    ap.add_argument("--out", default="pilot_report", help="output folder")
    ap.add_argument("--selftest", action="store_true", help="synthetic data into Saved/PilotReport_SELFTEST (not results)")
    a = ap.parse_args()
    if a.selftest:
        selftest()
        return
    if not a.logs:
        ap.error("--logs is required (or --selftest)")
    events = load_events(a.logs)
    if any(str(e.get("participant", "")).startswith("SYN-") for e in events):
        sys.exit("refusing: these logs contain synthetic participants (SYN-*). Real reports use real logs only.")
    print("report:", build_report(events, load_survey(a.survey), a.out))


if __name__ == "__main__":
    main()
